/**
 * Config plugin: SEC-10 / FR-APP-4 native hardening applied at `expo prebuild` / EAS build time.
 *
 * 1. Android: res/xml/network_security_config.xml with cleartextTrafficPermitted="false" and, when pins are
 *    given, a <pin-set> for the API host. android:usesCleartextTraffic="false" on <application>.
 *    OkHttp (React Native's HTTP stack) validates through the platform TrustManager, which enforces pin-set.
 * 2. iOS: NSAppTransportSecurity.NSPinnedDomains (iOS 14+). `pinKind: 'leaf'` (default) writes
 *    NSPinnedLeafIdentities (server key SPKI, as printed by the openssl command below); `pinKind: 'ca'` writes
 *    NSPinnedCAIdentities (intermediate/root SPKI). Android's pin-set matches any certificate in the chain, so
 *    the same pins work there. NSURLSession (React Native's fetch on iOS) enforces ATS pinning natively.
 *    `allowCleartext: true` (development builds only) permits http so the app can load its bundle from Metro;
 *    preview/production builds always ship with cleartext disabled.
 * 3. Android FLAG_SECURE (optional, `flagSecure: true`): blocks screenshots/screen recording and blanks the
 *    recents thumbnail for the whole activity. Without expo-screen-capture there is no per-screen toggle, so the
 *    whole app is protected when enabled (recommended for production; it is a PHI app).
 *
 * 4. Android release obfuscation (`minify: true`): R8 minify + resource shrinking via gradle.properties
 *    (android.enableMinifyInReleaseBuilds / android.enableShrinkResourcesInReleaseBuilds). JS ships as Hermes
 *    bytecode. Add keep rules to android/app/proguard-rules.pro if a native module needs them.
 *
 * Pins are base64 SHA-256 of the SubjectPublicKeyInfo. Always ship at least two (current + backup key).
 * Generate: openssl s_client -connect api.example:443 -servername api.example </dev/null \
 *   | openssl x509 -pubkey -noout | openssl pkey -pubin -outform der | openssl dgst -sha256 -binary | base64
 *
 * NOT verified on a device in this repository: run a staging build against a host with a wrong pin and confirm
 * requests fail before release (see README "Certificate pinning").
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withGradleProperties, withInfoPlist, withMainActivity } = require('expo/config-plugins');

function networkSecurityXml({ pinHost, pins, pinExpiration, allowCleartext }) {
  const pinSet = pins.length
    ? `\n    <pin-set expiration="${pinExpiration}">\n${pins.map((p) => `      <pin digest="SHA-256">${p}</pin>`).join('\n')}\n    </pin-set>`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withSecurityHardening.js. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${allowCleartext ? 'true' : 'false'}">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="false">${pinHost}</domain>${pinSet}
  </domain-config>
</network-security-config>
`;
}

const withAndroidNetworkSecurity = (config, opts) => {
  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), networkSecurityXml(opts));
      return c;
    },
  ]);
  return withAndroidManifest(config, (c) => {
    const app = c.modResults.manifest.application && c.modResults.manifest.application[0];
    if (app) {
      app.$['android:usesCleartextTraffic'] = opts.allowCleartext ? 'true' : 'false';
      app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    }
    return c;
  });
};

const withIosPinning = (config, { pinHost, pins, pinKind, allowCleartext }) =>
  withInfoPlist(config, (c) => {
    const ats = c.modResults.NSAppTransportSecurity || {};
    ats.NSAllowsArbitraryLoads = false;
    // Development builds load the JS bundle from Metro over http on the LAN.
    if (allowCleartext) ats.NSAllowsLocalNetworking = true;
    else delete ats.NSAllowsLocalNetworking;
    if (pins.length) {
      ats.NSPinnedDomains = {
        [pinHost]: {
          NSIncludesSubdomains: false,
          [pinKind === 'ca' ? 'NSPinnedCAIdentities' : 'NSPinnedLeafIdentities']: pins.map((p) => ({ 'SPKI-SHA256-BASE64': p })),
        },
      };
    }
    c.modResults.NSAppTransportSecurity = ats;
    return c;
  });

const withFlagSecure = (config) =>
  withMainActivity(config, (c) => {
    const src = c.modResults.contents;
    if (src.includes('FLAG_SECURE')) return c;
    if (c.modResults.language === 'kt') {
      const anchor = /super\.onCreate\([^)]*\)/;
      if (!anchor.test(src)) {
        console.warn('[withSecurityHardening] MainActivity.onCreate not found; FLAG_SECURE not applied');
        return c;
      }
      c.modResults.contents = src.replace(
        anchor,
        (m) => `${m}\n    // SEC-10: block screenshots/recording of clinical data\n    window.setFlags(android.view.WindowManager.LayoutParams.FLAG_SECURE, android.view.WindowManager.LayoutParams.FLAG_SECURE)`,
      );
    } else {
      console.warn('[withSecurityHardening] Java MainActivity not supported; FLAG_SECURE not applied');
    }
    return c;
  });

const withReleaseMinify = (config) =>
  withGradleProperties(config, (c) => {
    for (const key of ['android.enableMinifyInReleaseBuilds', 'android.enableShrinkResourcesInReleaseBuilds']) {
      c.modResults = c.modResults.filter((p) => !(p.type === 'property' && p.key === key));
      c.modResults.push({ type: 'property', key, value: 'true' });
    }
    return c;
  });

module.exports = function withSecurityHardening(config, props = {}) {
  const opts = {
    pinHost: props.pinHost || 'api.healthflow.eg',
    pins: Array.isArray(props.pins) ? props.pins : [],
    pinExpiration: props.pinExpiration || '2027-12-31',
    pinKind: props.pinKind === 'ca' ? 'ca' : 'leaf',
    flagSecure: !!props.flagSecure,
    allowCleartext: !!props.allowCleartext,
    minify: props.minify !== false,
  };
  if (opts.pins.length === 1) console.warn('[withSecurityHardening] only one pin configured; add a backup pin');
  if (!opts.pins.length) console.warn('[withSecurityHardening] CERT_PINS empty: TLS pinning disabled for this build');
  config = withAndroidNetworkSecurity(config, opts);
  config = withIosPinning(config, opts);
  if (opts.flagSecure) config = withFlagSecure(config);
  if (opts.minify) config = withReleaseMinify(config);
  return config;
};
